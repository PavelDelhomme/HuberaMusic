export function youtubeCookiesFingerprint(): string {
  const h = resolveYoutubeCookieHeader() || '';
  const f = resolveYoutubeCookiesFileForYtDlp() || '';
  return createHash('sha256').update(h + '|' + f).digest('hex').slice(0, 16);
}

export function youtubeCookiesStatus(): YoutubeCookiesStatus {
  const header = resolveYoutubeCookieHeader();
  const netscape = resolveYoutubeCookiesFileForYtDlp();
  const appEnv = String(process.env.APP_ENV || 'local').toLowerCase();
  let source: YoutubeCookiesStatus['source'] = null;
  if ((process.env.YOUTUBE_COOKIES || '').trim()) source = 'env';
  else if (existsSync(YT_COOKIE_HEADER_PATH) && readFileSync(YT_COOKIE_HEADER_PATH, 'utf8').trim())
    source = 'header-file';
  else if (netscape) source = 'netscape-file';
  else if (header) source = 'ytm-account';

  return {
    configured: Boolean(header || netscape),
    source,
    headerPath: YT_COOKIE_HEADER_PATH,
    netscapePath: YT_COOKIE_NETSCAPE_PATH,
    hint: header || netscape
      ? 'Session navigateur optionnelle (anti-bot). Pas de Premium requis — stream OK aussi sans cookies.'
      : appEnv === 'local' || appEnv === 'development'
        ? 'Aucun cookie YouTube — normal. Stream via yt-dlp/Innertube sans Premium.'
        : 'Aucun cookie — OK. Préfère STREAM_UPSTREAM (PC maison) ; cookies navigateur optionnels, jamais Premium.',
  };
}

/** Sauvegarde un header Cookie=… ou un fichier Netscape. */
export function saveYoutubeCookieHeader(raw: string) {
  let text = String(raw || '').trim();
  if (looksLikeNetscape(text)) {
    const header = netscapeToCookieHeader(text);
    if (header.length < 40) {
      throw new Error('Fichier Netscape sans cookies utiles');
    }
    writeFileSync(YT_COOKIE_NETSCAPE_PATH, text.endsWith('\n') ? text : `${text}\n`, 'utf8');
    writeFileSync(YT_COOKIE_HEADER_PATH, `${header}\n`, 'utf8');
    return youtubeCookiesStatus();
  }

  const cleaned = text.replace(/^Cookie:\s*/i, '');
  if (cleaned.length < 40) {
    throw new Error('Cookie trop court — utilise bash scripts/push-youtube-cookies.sh');
  }
  writeFileSync(YT_COOKIE_HEADER_PATH, `${cleaned}\n`, 'utf8');
  writeFileSync(YT_COOKIE_NETSCAPE_PATH, cookieHeaderToNetscape(cleaned), 'utf8');
  return youtubeCookiesStatus();
}

export function clearYoutubeCookieHeader() {
  writeFileSync(YT_COOKIE_HEADER_PATH, '', 'utf8');
  try {
    if (existsSync(YT_COOKIE_NETSCAPE_PATH)) unlinkSync(YT_COOKIE_NETSCAPE_PATH);
  } catch {
    writeFileSync(YT_COOKIE_NETSCAPE_PATH, '', 'utf8');
  }
  return youtubeCookiesStatus();
}
